# G15 — regression pins of the existing single-chain and PT drivers
# (docs/specs/constrained-mc.md D4, mover refactor of run.jl).
#
# THIS IS A CHANGE DETECTOR, NOT CORRECTNESS EVIDENCE. The values below are what the
# code produced, not what the physics requires; they pin behavior so that a refactor
# of the driver layer (the mover methods of `_compound_sweep!` / `_run_temperature!`
# / `_mc_loop!`) cannot silently change the RNG consumption or the update order of
# `run_mc` (with and without overrelaxation, `carryover` true and false) or of
# `run_pt` (whose lanes call the 5-argument `_compound_sweep!`). Any such change
# moves these numbers by O(1), not by rounding. Correctness of the samplers is
# gated elsewhere (test_metropolis.jl, test_overrelaxation.jl, test_pt.jl).
#
# Captured: commit 6cc6771 (before the mover refactor; a `git archive` of that
# commit), SCEFitting 4d2f86e, Julia 1.12.7, macOS 15.7 (Apple silicon, arm64),
# 2026-11-21, `JULIA_NUM_THREADS = 4` (the results do not depend on the thread
# count). The refactored code reproduced every value bitwise on the same machine.
# `mc_or` runs three temperatures with `carryover = false` so that the
# uniform-random restart is drawn twice: with one restart, a restart drawn from a
# COPY of the chain stream (not advancing it) is invisible.
#
# Platform scope: compared only on the capture platform class (macOS, aarch64,
# Julia 1.12) and skipped elsewhere. A trajectory is not portable at rtol: a
# rounding-level difference of one ΔE (another libm, another CPU's FMA use) can
# flip one accept decision, which changes the RNG consumption from then on and
# moves the whole trajectory by O(1). On the capture class the comparison is at
# rtol 1e-10 (vector norm per observable).
#
# Recapture ONLY with the user's approval, and only when one of these changed on
# purpose: the RNG consumption or the update order of the drivers; SCEFitting's
# `Harmonics` (or the LegendrePolynomials recursions it calls); the Julia minor
# version (the `Xoshiro` / `randn` / range-sampling streams) — verify that the
# change is the cause first. Run `_g15_print_pin()` on the capture platform and
# paste its output over `_G15_PIN`.
#
# The observables and evaluables are named explicitly (filtered from the standard
# sets), so adding a standard observable does not move the pin.

const _G15_OBSERVABLES = (:energy, :energy2, :m, :absm, :m2, :m4, :sublattice_m)
const _G15_EVALUABLES = (:specific_heat, :susceptibility, :binder)

const _G15_PLATFORM = Sys.isapple() && Sys.ARCH === :aarch64 &&
                      VERSION.major == 1 && VERSION.minor == 12

_g15_hamiltonian() = MC.TiledHamiltonian(3, _f3a_terms(); dims = (2, 2, 1))

function _g15_runs(H)
    common = (; sweeps_therm = 200, sweeps_measure = 400, adapt_interval = 20,
              renorm_interval = 150, nbins = 8,
              observables = filter(o -> o.name in _G15_OBSERVABLES,
                                   standard_observables(H)),
              evaluables = filter(e -> e.name in _G15_EVALUABLES,
                                  standard_evaluables()))
    @assert length(common.observables) == length(_G15_OBSERVABLES)
    @assert length(common.evaluables) == length(_G15_EVALUABLES)
    mc_plain = run_mc(H; kT = [0.02, 0.01], common..., seed = 1501)
    mc_or = run_mc(H; kT = [0.03, 0.02, 0.01], common..., or_per_metropolis = 2,
                   carryover = false, seed = 1502)
    pt = run_pt(H; kT = [0.03, 0.02, 0.01], common..., or_per_metropolis = 1,
                exchange_interval = 5, seed = 1503)
    return (; mc_plain, mc_or, pt)
end

# The pinned quantities of one result, in the shape of `_G15_PIN`: per point (kT,
# acceptances, final step, and `name => (mean, err)` for every stat in sorted-name
# order), then the final configuration(s) flattened.
function _g15_digest(r)
    points = [(; kT = p.kT, acc_m = p.acceptance_metropolis, acc_o = p.acceptance_or,
               step = p.final_step,
               stats = [k => (p.stats[k].mean, p.stats[k].err)
                        for k in sort(collect(keys(p.stats)))])
              for p in r.points]
    configs = r isa MCResult ? [r.final_config] : r.final_configs
    final = Float64[x for c in configs for e in c for x in e]
    return (; points, final)
end

# Print `_G15_PIN` from a fresh run, ready to paste over the literal below (values
# with `repr`, which round-trips Float64 exactly; wrapped at 3 numbers per line).
function _g15_print_pin(io::IO = stdout)
    runs = _g15_runs(_g15_hamiltonian())
    arr(v, pad) = "[" * join([join(repr.(v[i:min(i + 2, end)]), ", ")
                              for i = 1:3:length(v)], ",\n" * " "^(pad + 1)) * "]"
    println(io, "const _G15_PIN = (")
    for name in (:mc_plain, :mc_or, :pt)
        d = _g15_digest(getfield(runs, name))
        println(io, "    $name = (points = [")
        for p in d.points
            println(io, "        (kT = $(repr(p.kT)), acc_m = $(repr(p.acc_m)), " *
                        "acc_o = $(repr(p.acc_o)),")
            println(io, "         step = $(repr(p.step)), stats = [")
            for (k, (m, e)) in p.stats
                println(io, "             $(repr(k)) => (")
                println(io, "                 " * arr(m, 17) * ",")
                println(io, "                 " * arr(e, 17) * "),")
            end
            println(io, "         ]),")
        end
        println(io, "    ],")
        println(io, "    final = " * arr(d.final, 12) * "),")
    end
    println(io, ")")
    return nothing
end


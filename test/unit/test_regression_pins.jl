@testset "G15: regression pins of run_mc / run_pt (change detector)" begin
    if !_G15_PLATFORM
        @info "G15 pins skipped: captured on macOS / aarch64 / Julia 1.12, and a " *
              "trajectory is not portable across platforms (one rounding-level ΔE " *
              "difference flips an accept decision and changes the RNG consumption)"
        @test_skip false
    else
        runs = _g15_runs(_g15_hamiltonian())
        for name in (:mc_plain, :mc_or, :pt)
            d = _g15_digest(getfield(runs, name))
            ref = getfield(_G15_PIN, name)
            @testset "$name" begin
                @test length(d.points) == length(ref.points)
                for (p, q) in zip(d.points, ref.points)
                    @test p.kT == q.kT
                    @test _g15_close(p.acc_m, q.acc_m)
                    @test isequal(p.acc_o, q.acc_o) || _g15_close(p.acc_o, q.acc_o)
                    @test _g15_close(p.step, q.step)
                    @test first.(p.stats) == first.(q.stats)
                    for ((k, (m, e)), (_, (m_ref, e_ref))) in zip(p.stats, q.stats)
                        ok = _g15_close(m, m_ref) && _g15_close(e, e_ref)
                        ok || @error "G15 pin moved" name p.kT k m m_ref e e_ref
                        @test ok
                    end
                end
                @test _g15_close(d.final, ref.final)
            end
        end
    end
end
